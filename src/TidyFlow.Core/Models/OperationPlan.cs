namespace TidyFlow.Core.Models;

public enum OperationKind
{
    Move,
    Rename,
    MoveAndRename
}

public enum OperationStatus
{
    Ready,
    Skipped,
    ConflictResolved,
    Warning,
    Error
}

/// <summary>
/// Represents a single planned file move or rename before execution (dry-run preview).
/// </summary>
public sealed record PlannedFileOperation(
    string SourcePath,
    string DestinationPath,
    OperationKind Kind,
    OperationStatus Status,
    string? Note = null)
{
    public string SourceName => Path.GetFileName(SourcePath);

    public string DestinationName => Path.GetFileName(DestinationPath);

    public bool WillModify => Status is OperationStatus.Ready
        or OperationStatus.ConflictResolved
        or OperationStatus.Warning;
}

/// <summary>
/// Holds the full dry-run preview plan generated by an organizer or renamer.
/// </summary>
public sealed record OperationPlan(
    IReadOnlyList<PlannedFileOperation> Operations,
    DateTimeOffset CreatedAt,
    string Summary)
{
    public int ReadyCount => Operations.Count(o => o.WillModify);

    public int SkippedCount => Operations.Count(o => o.Status == OperationStatus.Skipped);

    public int ConflictResolvedCount => Operations.Count(o => o.Status == OperationStatus.ConflictResolved);

    public int ErrorCount => Operations.Count(o => o.Status == OperationStatus.Error);

    public bool HasErrors => ErrorCount > 0;
}
